/** 别名: 面板里同一个含义的标签可能写成不同的措辞 */
const ALIASES = {}

/** 归一化: 去掉 Vue 模板表达式与数字, 让 "L{{ active + 1 }} 分布" / "L3 分布" 都能命中 */
function normalize(label) {
  return String(label)
    .replace(/\{\{[^}]*\}\}/g, '')
    .replace(/\d+/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

/** 查说明: 精确 -> 归一化 -> 别名 */
export function docFor(label) {
  if (!label) return ''
  const key = String(label).trim()
  if (PARAM_DOCS[key]) return PARAM_DOCS[key]
  const norm = normalize(key)
  if (PARAM_DOCS[norm]) return PARAM_DOCS[norm]
  const normNoSpace = norm.replace(/\s+/g, '')
  for (const [k, v] of Object.entries(PARAM_DOCS)) {
    if (normalize(k).replace(/\s+/g, '') === normNoSpace) return v
  }
  if (ALIASES[key] && PARAM_DOCS[ALIASES[key]]) return PARAM_DOCS[ALIASES[key]]
  if (ALIASES[norm] && PARAM_DOCS[ALIASES[norm]]) return PARAM_DOCS[ALIASES[norm]]
  return ''
}

export const DOC_KEYS = Object.keys(PARAM_DOCS)
