/**
 * 自动风场: 由种子推导"说得通"的一套风参数
 * ------------------------------------------------------------
 * 量级约定: strength 是"树梢顺风偏移"的米数量级。
 * 默认档位 (k≈0.3) 只有十几厘米 —— 目的是"树叶在动、树干基本不动";
 * 大风档 (k=1) 到 ~0.35m, 需要狂风再往上推。
 * 单独成模块是为了让 species.js 与 presets.js 都能用而不产生循环依赖。
 *
 * 作用: 用户只给一个 `intensity` (风力总滑杆 0..1), 这里把它"展开"成
 *       `params.wind` 的十几个物理/表现参数, 让不同风力档位在视觉上是一套连贯的气象条件,
 *       而不是十几根各自乱调的滑杆。
 * 输入 / 输出: `(seed, intensity)` -> 一个**完整的** `params.wind` 子对象 (见下方字段注释)。
 * 调用方 / 时机:
 *   - `params.js` 的默认参数 + `presets.js` 生成树种预设时会调用;
 *   - `store/treeStore.js` 在"种子变了 / 风力滑杆变了 / 打开自动模式 / 换树种"时
 *     用 `Object.assign(state.params.wind, autoWind(...))` **覆盖式**写回;
 *   - 因此本函数必须每次返回全部字段 (不能只返回变化项), 否则旧值会残留。
 * 关键约定 (确定性纪律):
 *   随机数一律来自 `makeRng(seed, 'auto-wind')` 这条带阶段标签的子流 ——
 *   同 seed + 同 intensity 必然得到同一套风参数; 且改其它模块的随机调用不会挪动这里的结果。
 * 注意: 所有数值都过 `+x.toFixed(3)`, 目的是把浮点尾巴收敛到 3 位小数:
 *       参数会被序列化进导出的参数 JSON / 触发 Vue 的深度 watch,
 *       保留 17 位有效数字只会让"看起来没变"的参数产生无效重建。
 */
import { makeRng } from './rng.js'

/**
 * 按种子 + 风力强度推导一整套风参数。
 *
 * 设计思路: 每条参数都是 `基准值 + k * 增量 * (0.75~1.25 的随机因子)` 这种形状 ——
 * 基准值保证 k=0 时仍有"微风"而不是绝对静止; 随机因子只做 ±15%~25% 的扰动,
 * 于是同一档风力在不同种子下"性格不同"但物理量级不跑偏。少数参数是**反向**关系
 * (k 越大值越小, 如 flexFalloff) —— 风越大树越"软", 沿枝条的柔度衰减反而更平缓。
 *
 * @param {number} seed 随机种子 (整数; 同一 seed 结果可复现)
 * @param {number} [intensity=0.5] 风力总强度 0..1; 越界会被夹到 [0,1]
 * @returns {object} `params.wind` 完整子对象 (字段含义见每个属性上的注释)
 */
export function autoWind(seed, intensity = 0.5) {
  // 专用随机子流: 标签 'auto-wind' 与其它阶段隔离, 保证"风参数只由 seed 决定"
  const rng = makeRng(seed, 'auto-wind')
  // 夹紧: NaN / 字符串 / 超界都收敛到 [0,1], 后面所有插值都假设 k 在这个区间
  const k = Math.max(0, Math.min(1, intensity))
  return {
    enabled: true,        // 风场开关: 自动推导出来的参数默认是"开"
    auto: true,           // 自动模式标记: true 时 UI 隐藏细调滑杆, 改风力就整体重算
    intensity: k,         // 用户总滑杆 (0..1), 原样回写, 保证 UI 与内部数值一致
    direction: Math.round(rng.range(0, 360)),   // 风向, 单位**度** (0..359); 只影响水平朝向, 不影响幅度
    // 树梢顺风偏移的米数量级: 0.03 是"几乎看不见的微风"底噪, k*0.3 线性放大到 ~0.33m
    strength: +(0.03 + k * 0.3 * rng.range(0.75, 1.25)).toFixed(3),
    // 摆动相位推进速度 (无量纲倍率): 乘在时间上, 越大摆动越快; 与 strength 解耦, 才能"大风慢摆"
    speed: +(0.45 + k * 0.95 * rng.range(0.85, 1.15)).toFixed(3),
    // 高频分量密度 (倍率): 放大叠加上去的 2.17 次波与湍流频率, 越大越"碎"
    frequency: +(0.6 + k * 0.9 * rng.range(0.85, 1.15)).toFixed(3),
    // 阵风强度 (0..1): 压低摆动低谷(=让风"一阵一阵"), 越大起伏越明显
    gust: +Math.min(1, 0.15 + k * 0.5 * rng.range(0.85, 1.15)).toFixed(3),
    // 阵风包络的角速度 (rad/s 量级): 0.06 是约十几秒一个周期, 越大"阵"越密
    gustSpeed: +(0.06 + k * 0.22 * rng.range(0.8, 1.2)).toFixed(3),
    // 垂直于风向的横向抖动幅度 (相对 strength 的比例): 只造"飘忽感", 不改变主风向
    turbulence: +(0.03 + k * 0.22 * rng.range(0.8, 1.2)).toFixed(3),
    // 相位的空间尺度 (1/米 量级): 让相邻叶片/枝条的相位错开, 避免整棵树像一块板一起动
    spatialScale: +(0.1 + k * 0.35 * rng.range(0.85, 1.15)).toFixed(3),
    // 顺风偏置 (0..1): 只抬高摆动低谷, 不削低峰值 —— 物理上"风只推不拉"
    bias: +(0.2 + k * 0.25).toFixed(3),
    // 柔度衰减指数: 沿枝条从基部到梢部, 可摆幅度的衰减曲线陡峭程度;
    // 风越大值越小(1.9 -> 1.4), 即整枝更均匀地弯, 而不是只有梢部猛甩
    flexFalloff: +(1.9 - k * 0.5).toFixed(3),
    // 树干/树枝摆幅倍率: 与叶片分开调, 用来保证"树干基本不动"的观感
    barkSway: +(0.4 + k * 0.5).toFixed(3),
    // 叶片扇动倍率: 单片叶子沿自身弯曲方向的高频小幅扇动
    leafFlutter: +(0.25 + k * 0.75 * rng.range(0.85, 1.2)).toFixed(3),
    // 叶片铰链俯仰角 (弧度量级): 叶片绕水平轴(垂直风向)的翻转幅度
    leafTwist: +(0.15 + k * 0.7 * rng.range(0.85, 1.2)).toFixed(3),
    timeScale: 1.0,       // 全局时间缩放: 自动风场固定 1.0, 留给"整体慢动作"这类特殊需求
  }
}
